/* Pressure–temperature (PT) saturation data for common refrigerants, used by
 * the refrigerant calculator to turn a gauge reading (psig) into a saturation
 * temperature (°F).
 *
 * Each row is [tempF, bubblePsig, dewPsig]:
 *   - bubble = liquid/high side, used for SUBCOOLING
 *   - dew    = vapor/low side, used for SUPERHEAT
 * For single-component / near-azeotropic refrigerants (R-22, R-134a, R-32,
 * R-410A) bubble and dew are equal or within rounding; the two columns are
 * still carried so the lookup is uniform. R-407C in particular has large glide
 * (~7–12°F), so picking the right column matters.
 *
 * Pressures are GAUGE psig (psia − 14.696). Data generated with CoolProp 7.2.0
 * (the open-source implementation of the NIST/REFPROP equations of state that
 * printed manufacturer PT charts are built from) and spot-checked against
 * published Chemours/Hudson R-22 values (40°F→68.6, 50°F→84.1, 75°F→132.2). */

export type RefRow = [tempF: number, bubblePsig: number, dewPsig: number];

export type Refrigerant = {
  id: string;
  /** Approximate temperature glide in °F (0 for single-component). */
  glide: number;
  rows: RefRow[];
};

/** Helper: build rows for a single-column refrigerant (bubble === dew). */
function single(pairs: [number, number][]): RefRow[] {
  return pairs.map(([t, p]) => [t, p, p]);
}

