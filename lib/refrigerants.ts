export function getRefrigerant(id: string): Refrigerant | undefined {
  return REFRIGERANTS.find((r) => r.id === id);
}

/**
 * Convert a gauge pressure (psig) to saturation temperature (°F) for the given
 * refrigerant, by linear interpolation between PT table anchor points.
 *
 * `side` selects the column: 'dew' for the low side (superheat), 'bubble' for
 * the high side (subcooling). Returns null when the pressure falls outside the
 * tabulated range (roughly −40°F to 140°F).
 */
export function satTempFromPressure(
  ref: Refrigerant,
  psig: number,
  side: 'bubble' | 'dew',
): number | null {
  const col = side === 'bubble' ? 1 : 2;
  const { rows } = ref;
  if (psig < rows[0][col] || psig > rows[rows.length - 1][col]) return null;

  for (let i = 0; i < rows.length - 1; i++) {
    const p0 = rows[i][col];
    const p1 = rows[i + 1][col];
    if (psig >= p0 && psig <= p1) {
      const t0 = rows[i][0];
      const t1 = rows[i + 1][0];
      const frac = p1 === p0 ? 0 : (psig - p0) / (p1 - p0);
      return t0 + frac * (t1 - t0);
    }
  }
  return null;
}
